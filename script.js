const key = "jamshedpur-october-progress";
let state = JSON.parse(localStorage.getItem(key) || "{}");

function esc(s) {
  return s.replace(
    /[&<>"']/g,
    (c) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#039;",
      })[c],
  );
}
function maps(q) {
  return q
    ? `<a class="map-btn" target="_blank" rel="noopener" href="${q}">Open in Maps ↗</a>`
    : "";
}
function render(week) {
  document
    .querySelectorAll(".week-btn")
    .forEach((b) => b.classList.toggle("active", b.dataset.week === week));
  const p = plans[week];
  document.getElementById("plan").innerHTML =
    `<div class="day"><h2>${esc(p.title)}</h2><p class="day-meta">Starting point: Dimna • Check each step when done.</p></div>` +
    p.days
      .map(
        (d, di) =>
          `<article class="day"><div class="day-head"><div><h2>${esc(d.date)}</h2><div class="day-meta">${d.steps.length} stops • relaxed pace • no alcohol plan</div></div><div class="day-cost">₹${d.cost} target</div></div><div class="route">${d.steps
            .map((s, i) => {
              const id = `${week}-${di}-${i}`,
                checked = !!state[id];
              return `<div class="step"><div class="dot">${i + 1}</div><div><div class="time">${esc(s[0])}</div><div class="place">${esc(s[1])}</div><div class="action">${esc(s[2])}</div>${s[2].toLowerCase().includes("walk") ? '<span class="walk">🚶 Walking segment</span>' : ""}<div class="buttons">${maps(s[3])}</div><div class="check"><label><input type="checkbox" data-id="${id}" ${checked ? "checked" : ""}> Done</label></div></div></div>`;
            })
            .join("")}</div></article>`,
      )
      .join("");
  document.querySelectorAll("input[data-id]").forEach((x) =>
    x.addEventListener("change", (e) => {
      state[e.target.dataset.id] = e.target.checked;
      localStorage.setItem(key, JSON.stringify(state));
      updateBudget();
    }),
  );
  updateBudget();
}
function updateBudget() {
  let total = Object.keys(plans).reduce(
    (a, k) => a + plans[k].days.reduce((b, d) => b + d.cost, 0),
    0,
  );
  document.getElementById("spentText").textContent =
    `₹${total.toLocaleString("en-IN")} planned`;
}
document
  .querySelectorAll(".week-btn")
  .forEach((b) => b.addEventListener("click", () => render(b.dataset.week)));
render("w1");
